def main():
    init_db()

    print("注入 50+ 测试岗位...")
    new = 0
    skipped = 0
    for job in TEST_JOBS:
        job["url_hash"] = make_hash(job["title"] + job["company"] + job["apply_url"])
        job_id = insert_job(job)
        if job_id:
            new += 1
        else:
            skipped += 1

    print(f"新增: {new}, 跳过(重复): {skipped}")

    # 打分
    print("\n正在为所有岗位打分和生成建议...")
    profile = build_profile()

    jobs = get_jobs(filters={}, order_by="created_at DESC", limit=100)
    jobs = [j for j in jobs if not j.get("advice", "")]

    if jobs:
        batch_score_and_advise(profile, jobs)
        db_path = os.path.join(os.path.dirname(__file__), "data", "jobs.db")
        for job in jobs:
            conn = sqlite3.connect(db_path)
            conn.execute(
                "UPDATE jobs SET score = ?, priority_level = ?, advice = ?, company_type = ?, difficulty = ?, difficulty_label = ? WHERE id = ?",
                (job["score"], job["priority_level"], job.get("advice", ""), job.get("company_type", "其他"),
                 job.get("difficulty", 50), job.get("difficulty_label", "适中"), job["id"]),
            )
            conn.commit()
            conn.close()

        stats = get_stats()
        print(f"\n打分完成! 有效岗位: {stats['total']}")
        print(f"优先级: {stats['by_priority']}")
        print(f"类型: {stats['by_type']}")

        # 按难度分布统计
        easy = sum(1 for j in jobs if j.get("difficulty_label") == "容易")
        mid = sum(1 for j in jobs if j.get("difficulty_label") == "适中")
        hard = sum(1 for j in jobs if j.get("difficulty_label") == "挑战")
        extreme = sum(1 for j in jobs if j.get("difficulty_label") == "冲刺")
        print(f"竞争难度: ⭐容易{easy} | ⭐⭐适中{mid} | ⭐⭐⭐挑战{hard} | ⭐⭐⭐⭐冲刺{extreme}")

        # Top 10
        jobs_sorted = sorted(jobs, key=lambda j: j["score"], reverse=True)
        print("\n=== TOP 10 ===")
        for i, j in enumerate(jobs_sorted[:10], 1):
            diff = j.get("difficulty_label", "适中")
            print(f"{i}. [{j['priority_level']} | {diff}] {j['title']} @ {j['company']} — {j['score']}分")


if __name__ == "__main__":
    main()
